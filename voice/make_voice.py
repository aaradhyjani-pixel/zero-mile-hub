"""Render the SPG bodyguard's lines as earpiece-radio clips and write voice/spg_audio.js (embedded by build.py).

  python3 voice/make_voice.py

macOS `say` with the Aman (en-IN) voice, slow and deliberate, with real pauses; ffmpeg then gives it a walkie-talkie
sound (band-limited, compressed, a squelch click at each end) so it reads as an earpiece, not a robot.
Keys are the exact on-screen lines, so the game plays a clip whenever the bodyguard says that line.
"""
import base64, json, os, subprocess, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
P = '[[slnc 450]]'
RW = {'27R': 'two seven right', '27C': 'two seven centre', '27L': 'two seven left', '28R': 'two eight right', '28C': 'two eight centre', '28L': 'two eight left'}
LINES = {
  'Sir. We have taken over your runways.': f'Sir. {P} We have taken over your runways.',
  'All of them. Yes, the long one too.': f'All of them. {P} Yes. The long one too.',
  'Sir. Delhi has brought its summit. We have taken over your runways.': f'Sir. {P} Delhi has brought its summit. {P} We have taken over your runways.',
  'Thank you for giving us your runways. Thank you for your support.': f'Thank you for giving us your runways. {P} Thank you for your support.',
  'Your holding stack is now the second-largest gathering in Nagpur today.': 'Your holding stack is now the second largest gathering in Nagpur today.',
  'Very impressive, sir.': 'Very impressive, sir.',
  'The three motorcades have met on the apron.': 'The three motorcades have met on the apron.',
  'Nobody will reverse. Talks are under way.': f'Nobody will reverse. {P} Talks are under way.',
  'Your runways shall now be cleared, in a staged manner.': 'Your runways shall now be cleared, in a staged manner.',
  'Thank you, sir, for this.': 'Thank you, sir, for this.',
  'And thank you for serving the nation.': 'And thank you, for serving the nation.',
  'Jai Hind.': 'Jai Hind.',
}
for k, v in RW.items():
    LINES[f'Runway {k} shall be cleared first.'] = f'Runway {v} shall be cleared first.'
    LINES[f'Then runway {k}.'] = f'Then, runway {v}.'
    LINES[f'And finally, runway {k}.'] = f'And finally, runway {v}.'
out = {}
with tempfile.TemporaryDirectory() as td:
    for i, (key, text) in enumerate(LINES.items()):
        a, m = os.path.join(td, f'{i}.aiff'), os.path.join(td, f'{i}.mp3')
        subprocess.run(['say', '-v', 'Aman', '-r', '158', '-o', a, text], check=True)
        fc = ('[0:a]aresample=24000,aformat=sample_fmts=fltp:channel_layouts=mono,highpass=f=300,lowpass=f=3400,'
              'acompressor=threshold=-20dB:ratio=5:attack=4:release=80,volume=1.9,asoftclip=type=tanh[s];'
              '[1:a]aresample=24000,aformat=sample_fmts=fltp:channel_layouts=mono,highpass=f=1500,volume=0.6[c1];'
              '[2:a]aresample=24000,aformat=sample_fmts=fltp:channel_layouts=mono,highpass=f=900,volume=0.45[c2];'
              '[3:a]aresample=24000,aformat=sample_fmts=fltp:channel_layouts=mono,lowpass=f=4000,volume=0.05[h];'
              '[s][h]amix=inputs=2:duration=first:normalize=0[sh];[c1][sh][c2]concat=n=3:v=0:a=1[o]')
        subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', a,
                        '-f', 'lavfi', '-t', '0.06', '-i', 'anoisesrc=c=white:a=0.5:r=24000',
                        '-f', 'lavfi', '-t', '0.09', '-i', 'anoisesrc=c=pink:a=0.5:r=24000',
                        '-f', 'lavfi', '-t', '30', '-i', 'anoisesrc=c=pink:a=1:r=24000',
                        '-filter_complex', fc, '-map', '[o]', '-c:a', 'libmp3lame', '-b:a', '40k', m], check=True)
        out[key] = 'data:audio/mpeg;base64,' + base64.b64encode(open(m, 'rb').read()).decode()
js = '// generated by voice/make_voice.py: the SPG bodyguard\'s lines as earpiece-radio clips, keyed by the on-screen line\nconst SPG_AUDIO=' + json.dumps(out) + ';\n'
open(os.path.join(HERE, 'spg_audio.js'), 'w').write(js)
print(len(out), 'clips', round(len(js) / 1024), 'KB')
